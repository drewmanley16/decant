import Foundation

/// Broad style of wine. Raw values match the `wine_type` Postgres enum.
enum WineType: String, Codable, CaseIterable, Sendable, Identifiable {
    case red, white, rose, sparkling, dessert, fortified, orange

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .red: "Red"
        case .white: "White"
        case .rose: "Rosé"
        case .sparkling: "Sparkling"
        case .dessert: "Dessert"
        case .fortified: "Fortified"
        case .orange: "Orange"
        }
    }
}

/// Where a piece of wine information came from. The UI must visually separate
/// verified facts from AI-generated suggestions.
enum InfoSource: String, Codable, Sendable {
    /// Confirmed against a licensed provider or curated by staff.
    case verified
    /// Read directly from the label (OCR / vision extraction).
    case label
    /// Curated editorial estimate (e.g. typical style of a wine).
    case editorial
    /// Generated by an AI model; never presented as fact.
    case aiSuggested = "ai_suggested"
    /// Entered by a user.
    case user

    var isFactual: Bool { self == .verified || self == .label }

    var badge: String {
        switch self {
        case .verified: "Verified"
        case .label: "From label"
        case .editorial: "Curated"
        case .aiSuggested: "AI suggestion"
        case .user: "User submitted"
        }
    }
}

struct GrapeShare: Codable, Hashable, Sendable {
    var name: String
    var percentage: Int?
}

struct Price: Codable, Hashable, Sendable {
    var amount: Decimal
    var currency: String

    var formatted: String {
        amount.formatted(.currency(code: currency).precision(.fractionLength(0)))
    }

    var doubleValue: Double { NSDecimalNumber(decimal: amount).doubleValue }
}

struct Winery: Codable, Hashable, Sendable, Identifiable {
    var id: UUID
    var name: String
    var country: String?
    var region: String?
    var foundedYear: Int?
    var story: String?
    var practices: [String]
    var highlights: [String]
    var source: InfoSource

    init(id: UUID = UUID(), name: String, country: String? = nil, region: String? = nil,
         foundedYear: Int? = nil, story: String? = nil, practices: [String] = [],
         highlights: [String] = [], source: InfoSource = .user) {
        self.id = id
        self.name = name
        self.country = country
        self.region = region
        self.foundedYear = foundedYear
        self.story = story
        self.practices = practices
        self.highlights = highlights
        self.source = source
    }
}

/// Structural / stylistic profile. Each axis is 0...1; nil means unknown.
struct WineCharacteristics: Codable, Hashable, Sendable {
    var sweetness: Double?
    var acidity: Double?
    var body: Double?
    var tannin: Double?
    var fruitiness: Double?
    var flavors: [String] = []
    var tastingNotes: String?
    var servingTempC: ClosedRange<Int>?
    var decantMinutes: Int?
    var agingPotentialYears: Int?
    var source: InfoSource

    var vector: [Double] {
        [sweetness ?? 0.3, acidity ?? 0.5, body ?? 0.5, tannin ?? 0.3, fruitiness ?? 0.5]
    }
}

/// The denormalized wine object the UI works with: one specific vintage of a
/// product, joined with its producer, profile and community stats.
/// `id` is the *vintage* id (`wine_vintages.id`).
struct Wine: Codable, Hashable, Sendable, Identifiable {
    var id: UUID
    var productID: UUID
    var name: String
    var winery: Winery
    var vintage: Int?
    var type: WineType
    var grapes: [GrapeShare]
    var country: String?
    var region: String?
    var appellation: String?
    var abv: Double?
    var bottleSizeML: Int
    var price: Price?
    var labelImagePath: String?
    var bottleImagePath: String?
    var drinkFrom: Int?
    var drinkUntil: Int?
    var characteristics: WineCharacteristics?
    var pairings: [String]
    var factsSource: InfoSource
    var communityRating: Double?
    var ratingsCount: Int

    var vintageLabel: String { vintage.map(String.init) ?? "NV" }
    var displayName: String { "\(name) \(vintageLabel)" }
    var producer: String { winery.name }

    var locationLine: String {
        [region ?? appellation, country].compactMap { $0 }.joined(separator: ", ")
    }

    var grapeLine: String {
        grapes.map { g in g.percentage.map { "\(g.name) \($0)%" } ?? g.name }.joined(separator: ", ")
    }

    var drinkingWindow: String? {
        switch (drinkFrom, drinkUntil) {
        case let (from?, until?): "\(from)–\(until)"
        case let (from?, nil): "From \(from)"
        case let (nil, until?): "Until \(until)"
        default: nil
        }
    }

    /// Stable key for "same wine, any vintage" comparisons.
    var productKey: UUID { productID }
}

/// Parameters for catalog search. All filters are optional and combined with AND.
struct WineSearchQuery: Sendable, Hashable {
    var text: String = ""
    var types: Set<WineType> = []
    var country: String?
    var region: String?
    var grape: String?
    var vintage: Int?
    var maxPrice: Double?
    var minRating: Double?

    var isEmpty: Bool {
        text.trimmingCharacters(in: .whitespaces).isEmpty && types.isEmpty && country == nil
            && region == nil && grape == nil && vintage == nil && maxPrice == nil && minRating == nil
    }
}

/// A draft used to create a wine that is not yet in the catalog (manual entry
/// or an unmatched scan). Only fields the user/label supplied are set.
struct WineDraft: Codable, Sendable, Hashable {
    var name: String = ""
    var producer: String = ""
    var vintage: Int?
    var type: WineType = .red
    var grapes: [String] = []
    var country: String = ""
    var region: String = ""
    var appellation: String = ""
    var abv: Double?
    var bottleSizeML: Int = 750
    var priceAmount: Double?
    var currency: String = "USD"
    var labelImagePath: String?
    var source: InfoSource = .user

    var isValid: Bool {
        !name.trimmingCharacters(in: .whitespaces).isEmpty && !producer.trimmingCharacters(in: .whitespaces).isEmpty
    }
}
