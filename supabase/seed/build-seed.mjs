// Builds the app's bundled seed catalog and supabase/seed.sql from
// catalog.source.json, using deterministic UUIDs so both stay in sync.
//   node supabase/seed/build-seed.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const source = JSON.parse(readFileSync(join(here, "catalog.source.json"), "utf8"));

function uuid(key) {
  const h = createHash("sha1").update(`decant:${key}`).digest("hex");
  const variant = ((parseInt(h[16], 16) & 0x3) | 0x8).toString(16);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${variant}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}
const slug = (s) => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-");
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;

const wineries = source.wineries.map((w) => ({ ...w, id: uuid(`winery:${w.key}`) }));
const wineryByKey = Object.fromEntries(wineries.map((w) => [w.key, w]));

const appWines = [];
const sql = [
  "-- Generated by supabase/seed/build-seed.mjs. Do not edit by hand.",
  "-- Development seed catalog (editorial). Replace with licensed provider data in production.",
  "begin;",
];

for (const w of wineries) {
  sql.push(
    `insert into public.wineries (id, name, country, region, founded_year, story, practices, highlights, source) values (${q(w.id)}, ${q(w.name)}, ${q(w.country)}, ${q(w.region)}, ${w.founded ?? "null"}, ${q(w.story)}, ${arr(w.practices)}, ${arr(w.highlights)}, 'editorial') on conflict (id) do nothing;`
  );
}

for (const wine of source.wines) {
  const winery = wineryByKey[wine.winery];
  const productID = uuid(`product:${slug(wine.name)}`);
  sql.push(
    `insert into public.wine_products (id, winery_id, name, type, country, region, appellation, grapes, source) values (${q(productID)}, ${q(winery.id)}, ${q(wine.name)}, '${wine.type}', ${q(wine.country)}, ${q(wine.region)}, ${q(wine.appellation)}, ${arr(wine.grapes)}, 'editorial') on conflict (id) do nothing;`
  );
  const p = wine.profile;
  sql.push(
    `insert into public.wine_characteristics (product_id, sweetness, acidity, body, tannin, fruitiness, flavors, tasting_notes, serve_min_c, serve_max_c, decant_minutes, aging_years, source) values (${q(productID)}, ${p.sweetness}, ${p.acidity}, ${p.body}, ${p.tannin}, ${p.fruitiness}, ${arr(p.flavors)}, ${q(p.notes)}, ${p.serve[0]}, ${p.serve[1]}, ${p.decant}, ${p.aging}, 'editorial') on conflict (product_id) do nothing;`
  );
  for (const pairing of wine.pairings) {
    sql.push(`insert into public.wine_pairings (product_id, name) values (${q(productID)}, ${q(pairing)}) on conflict do nothing;`);
  }
  for (const v of wine.vintages) {
    const vintageID = uuid(`vintage:${slug(wine.name)}:${v.year ?? "nv"}`);
    sql.push(
      `insert into public.wine_vintages (id, product_id, year, bottle_size_ml, price_estimate, currency, drink_from, drink_until, source) values (${q(vintageID)}, ${q(productID)}, ${v.year ?? "null"}, 750, ${v.price}, 'USD', ${v.drink?.[0] ?? "null"}, ${v.drink?.[1] ?? "null"}, 'editorial') on conflict (id) do nothing;`
    );
    appWines.push({
      id: vintageID,
      productID,
      wineryID: winery.id,
      name: wine.name,
      type: wine.type,
      country: wine.country,
      region: wine.region,
      appellation: wine.appellation,
      grapes: wine.grapes,
      year: v.year,
      price: v.price,
      drinkFrom: v.drink?.[0] ?? null,
      drinkUntil: v.drink?.[1] ?? null,
      profile: p,
      pairings: wine.pairings,
    });
  }
}
sql.push("commit;", "");

const appCatalog = {
  wineries: wineries.map(({ key, ...w }) => w),
  wines: appWines,
};
writeFileSync(join(root, "Decant", "Resources", "SeedCatalog.json"), JSON.stringify(appCatalog, null, 1));
writeFileSync(join(root, "supabase", "seed.sql"), sql.join("\n"));
console.log(`Wrote ${wineries.length} wineries, ${appWines.length} vintages.`);
